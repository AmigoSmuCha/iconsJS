"""Writes the icon pack's resources from icons.py: one vector + adaptive icon per
design, appfilter.xml (which app gets which icon), drawable.xml (the picker)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import icons
from icons import ICONS, build, apps, Icon, calendar_day, GROUND
exec(open(os.path.join(HERE, "order.py")).read())
RES = os.path.join(HERE, "..", "app", "res")
DR, XML = os.path.join(RES, "drawable"), os.path.join(RES, "xml")
os.makedirs(DR, exist_ok=True); os.makedirs(XML, exist_ok=True)

def vector(icon):
    out = ['<vector xmlns:android="http://schemas.android.com/apk/res/android" '
           'android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for d, fill, stroke, w, cap, join in icon.parts:
        if fill:
            out.append('<path android:pathData="%s" android:fillColor="%s"/>' % (d, fill))
        else:
            out.append('<path android:pathData="%s" android:strokeColor="%s" android:strokeWidth="%s" '
                       'android:strokeLineCap="%s" android:strokeLineJoin="%s"/>' % (d, stroke, w, cap, join))
    return "\n".join(out + ["</vector>\n"])

def write(name, icon):
    open(os.path.join(DR, name + "_fg.xml"), "w").write(vector(icon))
    open(os.path.join(DR, name + ".xml"), "w").write(
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '<background android:drawable="@color/ground"/>\n'
        '<foreground android:drawable="@drawable/%s_fg"/>\n</adaptive-icon>\n' % name)

for key in ICONS:
    write("ic_" + key, build(key))
for day in range(1, 32):
    i = Icon(); calendar_day(i, day); write("calendar_%d" % day, i)
app = Icon("#fe8019"); app.dot(7.5, 12, 3, "o"); app.rect(12.5, 8.5, 7, 7)   # iconJS's own
write("ic_app", app)

af = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
for comp, key in apps():
    af.append('<item component="ComponentInfo{%s}" drawable="ic_%s"/>' % (comp, key))
    if key == "calendar":
        af.append('<calendar component="ComponentInfo{%s}" prefix="calendar_"/>' % comp)
af.append("</resources>")
open(os.path.join(XML, "appfilter.xml"), "w").write("\n".join(af) + "\n")
dx = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>", '<version>1</version>', '<category title="iconJS"/>']
dx += ['<item drawable="ic_%s"/>' % k for k in icons.ORDER]
open(os.path.join(XML, "drawable.xml"), "w").write("\n".join(dx + ["</resources>"]) + "\n")
open(os.path.join(HERE, "..", "app", "src", "com", "iconjs", "Icons.java"), "w").write(
    "package com.iconjs;\n\n/** Generated by tools/gen_android.py. */\nfinal class Icons {\n    static final String[] KEYS = {%s};\n    static final String[] LABELS = {%s};\n}\n"
    % (", ".join('"ic_%s"' % k for k in icons.ORDER), ", ".join('"%s"' % ICONS[k][0] for k in icons.ORDER)))
print(len(ICONS), "icons,", len(apps()), "apps, 31 calendar days")
